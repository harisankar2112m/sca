import pandas as pd
import plotly.express as px
import streamlit as st

from core.data import DATA, get_ds, load_ppac, load_sample
from core.forecast import forecast_upload
from core.validation import validate_outlets, validate_sales, validate_stock

st.title("Data")
ds = get_ds()

tab1, tab2, tab3, tab4 = st.tabs(["Current dataset", "Upload your data", "Templates & data dictionary", "Market data (PPAC)"])

with tab1:
    is_sample = ds["source"].startswith("Built-in")
    (st.info if is_sample else st.success)(f"**In use:** {ds['source']}")
    s, o = ds["sales"], ds["outlets"]
    c = st.columns(5)
    c[0].metric("Outlets", o["outlet_id"].nunique())
    c[1].metric("Series", s.groupby(["outlet_id", "product"]).ngroups)
    c[2].metric("History", f"{s['date'].min():%b %y} – {s['date'].max():%b %y}")
    c[3].metric("Days", f"{s['date'].nunique():,}")
    c[4].metric("Rows", f"{len(s):,}")
    if is_sample:
        st.warning("**Synthetic data disclosure.** Outlet sales, stock and deliveries are generated by the team "
                   "(OMCs do not publish outlet data). Demand follows real PPAC monthly trend and seasonality, real "
                   "festival / strike dates and the 2026 diesel price-gap shift. Generator script, seed and parameters "
                   "are in the project files.", icon="⚠️")
    st.markdown("**Outlet master**")
    st.dataframe(o, hide_index=True, width="stretch", height=250)
    st.markdown("**Daily sales and stock (latest 200 rows)**")
    st.dataframe(s.tail(200), hide_index=True, width="stretch", height=250)
    if not is_sample and st.button("Switch back to the built-in sample data"):
        st.session_state.ds = load_sample()
        st.rerun()

with tab2:
    st.markdown("""Upload your own outlet data as **CSV** files (use the templates in the next tab).
* **Daily sales** (required): `date, outlet_id, product, sales_kL, closing_stock_kL` — at least 2 years per outlet-product.
* **Outlet master** (required): tank capacities, dead stock and transit days for each outlet.
* **Current stock** (optional): today's dip readings. If omitted, the last `closing_stock_kL` in the sales file is used.

The app checks every file and refits the forecasting model (same ETS family JMP selected) on your data.""")
    f_sales = st.file_uploader("Daily sales CSV", type="csv", key="up_sales")
    f_out = st.file_uploader("Outlet master CSV", type="csv", key="up_outlets")
    f_stock = st.file_uploader("Current stock CSV (optional)", type="csv", key="up_stock")
    if st.button("Validate and load", type="primary", disabled=not (f_sales and f_out)):
        outlets, e1, w1 = validate_outlets(f_out)
        sales, e2, w2 = validate_sales(f_sales)
        errors, warns = [f"Outlet file: {e}" for e in e1] + [f"Sales file: {e}" for e in e2], w1 + w2
        if sales is not None and outlets is not None:
            unknown = set(sales["outlet_id"]) - set(outlets["outlet_id"])
            if unknown:
                errors.append(f"Sales file has outlet_id(s) missing from the outlet master: {', '.join(sorted(unknown)[:8])}")
        stock = None
        if f_stock and outlets is not None:
            stock, e3, w3 = validate_stock(f_stock, outlets)
            errors += [f"Stock file: {e}" for e in e3]; warns += w3
        for w in warns:
            st.warning(w)
        if errors:
            for e in errors:
                st.error(e)
            st.stop()
        as_of = sales["date"].max()
        if stock is None:
            stock = sales[sales["date"] == as_of][["outlet_id", "product", "closing_stock_kL"]] \
                .rename(columns={"closing_stock_kL": "current_stock_kL"}).dropna().assign(as_of_date=as_of)
            if stock.empty:
                st.error("No closing stock on the last date; upload a current stock file.")
                st.stop()
        else:
            as_of = stock["as_of_date"].max()
        bar = st.progress(0.0, "Fitting forecasting models…")
        fc, models = forecast_upload(sales, outlets, progress=lambda f, t: bar.progress(f, t))
        bar.empty()
        st.session_state.ds = dict(source=f"Uploaded files ({f_sales.name})", forecast_engine="Python ETS (JMP model family)",
                                   outlets=outlets, sales=sales, forecast=fc, models=models,
                                   stock=stock.reset_index(drop=True), as_of=pd.Timestamp(as_of))
        st.success(f"Loaded {sales.groupby(['outlet_id', 'product']).ngroups} series. All pages now use your data.")
        st.rerun()

with tab3:
    st.markdown("**Blank templates**")
    c = st.columns(3)
    for col, (fname, label) in zip(c, [("template_daily_sales.csv", "Daily sales template"),
                                       ("template_outlets.csv", "Outlet master template"),
                                       ("template_current_stock.csv", "Current stock template")]):
        col.download_button(label, (DATA / "templates" / fname).read_bytes(), file_name=fname, mime="text/csv")
    st.markdown("**Sample files** (the built-in data, for a quick test of the upload)")
    c = st.columns(2)
    smp = load_sample()
    c[0].download_button("Sample daily sales (CSV)", smp["sales"][["date", "outlet_id", "product", "sales_kL", "closing_stock_kL"]]
                         .to_csv(index=False, date_format="%Y-%m-%d"), file_name="sample_daily_sales.csv", mime="text/csv")
    c[1].download_button("Sample outlet master (CSV)", smp["outlets"].to_csv(index=False), file_name="sample_outlets.csv", mime="text/csv")
    with st.expander("Data dictionary", expanded=True):
        st.markdown((DATA / "DATA_DICTIONARY.md").read_text())

with tab4:
    p = load_ppac()
    st.markdown("Real all-India monthly consumption from **PPAC** (Ministry of Petroleum & Natural Gas). "
                "Used to calibrate the trend and seasonality of the outlet data.")
    prod = st.radio("Product", ["MS", "HSD"], horizontal=True, format_func=lambda x: {"MS": "Petrol (MS)", "HSD": "Diesel (HSD)"}[x])
    q = p[p["product"] == prod].copy()
    q["yoy_%"] = (q["consumption_tmt"].pct_change(12) * 100).round(1)
    fig = px.bar(q, x="month", y="consumption_tmt", labels={"consumption_tmt": "'000 tonnes", "month": ""},
                 color_discrete_sequence=["#2f6fdf" if prod == "MS" else "#d9822b"])
    fig.update_layout(height=320, margin=dict(t=10, b=10))
    st.plotly_chart(fig, width="stretch")
    st.dataframe(q[["month", "consumption_tmt", "consumption_million_litres", "yoy_%", "ppac_updated"]],
                 hide_index=True, width="stretch", height=240)
